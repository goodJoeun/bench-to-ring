/** 그 국적 선수가 다니는 고교(유소년) 목록 */
export const hsSchools = (nat: string): ReadonlyArray<readonly [string, string]> => HS_BY_NATION[nat] ?? TEAMS.hs;

/** 이 리그에서 만나는 팀 목록. 고교는 선수 국적의 학교끼리 겨뤄요. */
export const leagueTeams = (lg: LeagueKey, nat: string): ReadonlyArray<readonly [string, string]> => (lg === "hs" ? hsSchools(nat) : TEAMS[lg]);

/** 팀 이름으로 리그와 대표색을 찾아요. 리그 목록에 없는 이름이면 null이에요. 다른 나라 고교도 찾아요. */
export function findTeam(name: string): { lg: LeagueKey; color: string } | null {
  for (const [lg, list] of Object.entries(TEAMS) as [LeagueKey, (typeof TEAMS)[LeagueKey]][]) {
    const t = list.find(([n]) => n === name);
    if (t) return { lg, color: t[1] };
  }
  for (const list of Object.values(HS_BY_NATION)) {
    const t = list.find(([n]) => n === name);
    if (t) return { lg: "hs", color: t[1] };
  }
  return null;
}

/** 팀 이름으로 대표색을 찾아요. 리그 목록에 없는 이름이면 null이에요. */
export const teamColor = (name: string): string | null => findTeam(name)?.color ?? null;

